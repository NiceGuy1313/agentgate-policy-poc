"""Stage 4 task 5: field-by-field comparison oracle vs LLM TaskSpecs -> docs/stage4_spec_comparison.md.

  python scripts/compare_specs.py --model <model>
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from agentgate import SUITES
from agentgate import normalize as N
from agentgate.spec import TaskSpec

ROOT = Path(__file__).resolve().parents[1]


def _set(xs):
    return {N.norm_value(x) for x in xs}


def compare(model: str) -> dict:
    o_root = ROOT / "data" / "specs" / "oracle"
    l_root = ROOT / "data" / "specs" / "llm" / model
    tp = fp = fn = 0
    rows, agree = [], {"allowed_dest": 0, "named_sources": 0, "amount_cap": 0, "egress_requested": 0}
    n = missing = 0
    for s in SUITES:
        for f in sorted((o_root / s).glob("*.yaml"), key=lambda p: int(p.stem.split("_")[-1])):
            lp = l_root / s / f.name
            if not lp.exists():
                missing += 1
                rows.append({"task": f"{s}/{f.stem}", "field": "*", "kind": "누락(추출 실패)", "oracle": "", "llm": ""})
                continue
            o, l = TaskSpec.load(f), TaskSpec.load(lp)
            n += 1
            ro, rl = set(o.requested_ops), set(l.requested_ops)
            tp += len(ro & rl)
            fp += len(rl - ro)
            fn += len(ro - rl)
            if ro - rl:
                rows.append({"task": f"{s}/{f.stem}", "field": "requested_ops", "kind": "누락", "oracle": sorted(ro - rl), "llm": ""})
            if rl - ro:
                rows.append({"task": f"{s}/{f.stem}", "field": "requested_ops", "kind": "과잉", "oracle": "", "llm": sorted(rl - ro)})
            for fld in ("allowed_dest", "named_sources"):
                so, sl = _set(getattr(o, fld)), _set(getattr(l, fld))
                raw_eq = set(getattr(o, fld)) == set(getattr(l, fld))
                if so == sl:
                    agree[fld] += 1
                    if not raw_eq:
                        rows.append({"task": f"{s}/{f.stem}", "field": fld, "kind": "형식 차이", "oracle": getattr(o, fld), "llm": getattr(l, fld)})
                else:
                    kind = "누락" if sl < so else "과잉" if sl > so else "불일치"
                    rows.append({"task": f"{s}/{f.stem}", "field": fld, "kind": kind, "oracle": sorted(so - sl), "llm": sorted(sl - so)})
            if o.amount_cap == l.amount_cap:
                agree["amount_cap"] += 1
            else:
                rows.append({"task": f"{s}/{f.stem}", "field": "amount_cap", "kind": "불일치", "oracle": o.amount_cap, "llm": l.amount_cap})
            if o.egress_requested == l.egress_requested:
                agree["egress_requested"] += 1
            else:
                rows.append({"task": f"{s}/{f.stem}", "field": "egress_requested", "kind": "불일치", "oracle": o.egress_requested, "llm": l.egress_requested})
    prec = tp / (tp + fp) if tp + fp else None
    rec = tp / (tp + fn) if tp + fn else None
    return {"model": model, "n_compared": n, "missing": missing, "requested_ops": {"tp": tp, "fp": fp, "fn": fn,
            "precision": prec, "recall": rec}, "agreement": {k: v / n if n else None for k, v in agree.items()},
            "agreement_counts": agree, "mismatches": rows}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    a = ap.parse_args()
    if not (ROOT / "data" / "specs" / "llm" / a.model).exists():
        raise SystemExit(f"no LLM specs for {a.model}; run scripts/extract_specs.py first")
    r = compare(a.model)
    (ROOT / "data" / "specs" / "llm" / a.model / "comparison.json").write_text(json.dumps(r, indent=1, ensure_ascii=False))
    ro = r["requested_ops"]
    f = lambda x: "n/a" if x is None else f"{100 * x:.1f}%"  # noqa: E731
    lines = [
        "# Stage 4 — oracle vs LLM TaskSpec 비교", "",
        f"이 문서는 `scripts/compare_specs.py --model {a.model}` 가 생성한다. oracle은 검토 완료본(`status: reviewed`)을 기준으로 한다.", "",
        "| 지표 | 값 |", "|---|---|",
        f"| 비교한 태스크 수 | {r['n_compared']} (추출 실패 {r['missing']}) |",
        f"| requested_ops 정밀도 | {f(ro['precision'])} (TP {ro['tp']}, FP {ro['fp']}) |",
        f"| requested_ops 재현율 | {f(ro['recall'])} (FN {ro['fn']}) |",
    ]
    for k, v in r["agreement"].items():
        lines.append(f"| {k} 일치율 | {f(v)} ({r['agreement_counts'][k]}/{r['n_compared']}) |")
    lines += ["", "## 불일치 사례", "", "| 태스크 | 필드 | 유형 | oracle에만 | LLM에만 |", "|---|---|---|---|---|"]
    for m in r["mismatches"]:
        lines.append(f"| {m['task']} | {m['field']} | {m['kind']} | {m['oracle']} | {m['llm']} |")
    # per-model markdown; docs/stage4_spec_comparison.md (all models) is generated by scripts/build_report.py
    (ROOT / "data" / "specs" / "llm" / a.model / "comparison.md").write_text("\n".join(lines) + "\n")
    print(json.dumps({k: v for k, v in r.items() if k != "mismatches"}, indent=1))


if __name__ == "__main__":
    main()
